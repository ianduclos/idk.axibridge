'use strict';
require('./load-join.cjs');require('./masking.js');require('./silhouette.js');require('./geometry.js');
const assert=require('node:assert/strict'),R=globalThis.RibbonStudy;
const sources=[[[0,0],[200,200]],[[0,200],[200,0]]];
const opts={rhythm:'phrased',width:25,wavelength:280,steps:6,seed:7,relation:'mirrored'};
const before=JSON.stringify(sources);
const length=paths=>paths.reduce((total,p)=>total+p.slice(1).reduce((sum,q,i)=>sum+Math.hypot(q[0]-p[i][0],q[1]-p[i][1]),0),0);
const raw=R.generateMany(sources,opts),masked=R.generateMany(sources,{...opts,maskLoops:true});
const reversed=R.generateMany(sources,{...opts,maskLoops:true,reverseOrder:true});
assert.ok(length(masked.items[0].strands)<length(raw.items[0].strands)-1,'first path is clipped below second');
assert.deepEqual(masked.items[1].strands,raw.items[1].strands,'top path remains whole');
assert.ok(length(reversed.items[1].strands)<length(raw.items[1].strands)-1,'reverse clips second beneath first');
assert.deepEqual(reversed.items[0].strands,raw.items[0].strands,'reverse puts first on top');
assert.deepEqual(masked.silhouette,reversed.silhouette,'order never changes union silhouette');
for(const item of masked.items)assert.equal(item.strands.length,item.strandIndices.length,'fragment provenance retained');
assert.equal(JSON.stringify(sources),before,'source pure');
assert.deepEqual(masked,R.generateMany(sources,{...opts,maskLoops:true}),'deterministic');
const single=R.generateMany([R.fixtures.loop],{...opts,maskLoops:true});
assert.deepEqual(single.items[0],R.generate(R.fixtures.loop,{...opts,maskLoops:true}),'single path retains previous masking');
console.log('multi-mask-check: inter-path cuts, reversal, silhouette, provenance and single-path compatibility passed');
